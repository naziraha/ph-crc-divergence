"""
Write data/PROVENANCE.md: every file under data/raw with size, file modification date (local time; the
download date unless the file was later copied) and SHA-256 checksum. Read-only for the data files.

Usage: python scripts/make_data_provenance.py
"""
import datetime as dt
import hashlib
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "data", "raw")
NOTES = {
    "GSE41258_series_matrix.txt.gz": "GEO series matrix (discovery cohort)",
    "GSE20916_series_matrix.txt.gz": "GEO series matrix",
    "GSE37364_series_matrix.txt.gz": "GEO series matrix",
    "GSE117606_series_matrix.txt.gz": "GEO series matrix (fetched by step01_prepare_GSE117606.py)",
    "GPL96.txt": "GEO platform annotation (GEOparse)",
    "GPL570.txt": "GEO platform annotation (GEOparse)",
    "GPL25373.txt": "GEO platform table (Brainarray ENTREZG CDF; no symbol column, not used for mapping)",
    "Homo_sapiens.gene_info.gz": "NCBI gene_info, Entrez -> symbol for GSE117606 (fetched by step01_prepare_GSE117606.py)",
    "GSE117606_cel_headers.csv": "array plate / scan date per GSM, written by scripts/gse117606_cel_headers.py",
    "GSE117606_samples_brief.txt": "GEO sample metadata summary (screening before addendum 6)",
    "GSE117606_series_brief.txt": "GEO series summary (screening before addendum 6)",
    "GSE41657_samples_brief.txt": "GEO metadata summary; cohort screened, not analysed",
    "GSE41657_series_brief.txt": "GEO metadata summary; cohort screened, not analysed",
    "TCGA.COAD.sampleMap_HiSeqV2.gz": "UCSC Xena TCGA hub, TCGA-COAD gene expression, log2(RSEM + 1)",
    "TCGA.COAD.sampleMap_COAD_clinicalMatrix.txt": "UCSC Xena TCGA hub, TCGA-COAD clinical matrix",
    "COAD_mc3_gene_level.txt": "UCSC Xena TCGA hub, TCGA-COAD MC3 gene-level mutation calls",
    "TCGA.COAD.sampleMap_Gistic2_all_data_by_genes.gz": "UCSC Xena TCGA hub, TCGA-COAD GISTIC2 gene-level copy number (continuous)",
}


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


rows = []
for dp, _, fs in os.walk(RAW):
    for f in sorted(fs):
        p = os.path.join(dp, f)
        rows.append((os.path.relpath(p, ROOT).replace("\\", "/"), os.path.getsize(p),
                     dt.datetime.fromtimestamp(os.path.getmtime(p)).strftime("%Y-%m-%d %H:%M"), sha256(p), NOTES.get(f, "")))
rows.sort()
L = ["# Data provenance", "",
     f"Generated {dt.date.today().isoformat()} by `scripts/make_data_provenance.py`. Raw files are never edited.",
     "**Downloaded** = download date (file modification time on the analysis laptop, local time UTC+8; the files were",
     "not copied or edited after download). SHA-256 values are those of the files used for the paper.", "",
     "| File | Bytes | Downloaded | SHA-256 | Content |", "|---|---|---|---|---|"]
L += [f"| `{p}` | {s:,} | {m} | `{h}` | {n} |" for p, s, m, h, n in rows]
L += ["", "Processed files (`data/processed/`) are regenerated by the step scripts and are not listed."]
with open(os.path.join(ROOT, "data", "PROVENANCE.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(L) + "\n")
print("\n".join(L))
